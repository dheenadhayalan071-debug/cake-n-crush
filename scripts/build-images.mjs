/**
 * Image pipeline
 * ----------------
 * Converts the editorial source photography in `assets-src/` into
 * responsive WebP derivatives under `public/images/<name>/`.
 *
 * For every source image we emit:
 *   - 3 widths (default 480 / 900 / 1400) as `<name>-<width>.webp`
 *   - a tiny blurred LQIP (base64 data URI) written to
 *     `src/components/media/image-manifest.js`
 *
 * Run with `npm run images` (also runs automatically before `npm run build`).
 */
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, 'assets-src');
const OUT_DIR = path.join(ROOT, 'public', 'images');
const MANIFEST = path.join(ROOT, 'src', 'components', 'media', 'image-manifest.js');

const WIDTHS = [480, 900, 1400];
const QUALITY = 78;

async function main() {
  let files = [];
  try {
    files = (await readdir(SRC_DIR)).filter((f) => /\.(jpe?g|png|webp|avif|tiff?)$/i.test(f));
  } catch {
    console.warn('[images] no assets-src directory found — skipping.');
    return;
  }

  if (files.length === 0) {
    console.warn('[images] no source images found — skipping.');
    return;
  }

  const manifest = {};

  for (const file of files.sort()) {
    const name = path.basename(file, path.extname(file));
    const dir = path.join(OUT_DIR, name);
    await mkdir(dir, { recursive: true });

    const image = sharp(path.join(SRC_DIR, file)).rotate();
    const meta = await image.metadata();
    const widths = WIDTHS.filter((w) => w <= meta.width);
    if (widths.length === 0) widths.push(meta.width);

    let largest = null;
    for (const width of widths) {
      const outfile = path.join(dir, `${name}-${width}.webp`);
      const info = await sharp(path.join(SRC_DIR, file))
        .rotate()
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: QUALITY, effort: 5 })
        .toFile(outfile);
      if (!largest || info.width > largest.width) {
        largest = { width: info.width, height: info.height };
      }
    }

    const lqip = await sharp(path.join(SRC_DIR, file))
      .rotate()
      .resize({ width: 24 })
      .blur(1.2)
      .webp({ quality: 40 })
      .toBuffer();

    manifest[name] = {
      src: `/images/${name}/${name}-${widths[widths.length - 1]}.webp`,
      srcset: widths.map((w) => `/images/${name}/${name}-${w}.webp ${w}w`).join(', '),
      width: largest.width,
      height: largest.height,
      aspect: +(largest.width / largest.height).toFixed(4),
      lqip: `data:image/webp;base64,${lqip.toString('base64')}`,
    };

    const size = (await stat(path.join(dir, `${name}-${widths[widths.length - 1]}.webp`))).size;
    console.log(
      `[images] ${name}: ${widths.join('/')}px · largest ${Math.round(size / 1024)} KB`,
    );
  }

  await mkdir(path.dirname(MANIFEST), { recursive: true });
  const source = `/**
 * AUTO-GENERATED by scripts/build-images.mjs — do not edit by hand.
 * Run \`npm run images\` after adding or changing files in assets-src/.
 */
export const IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)};
`;
  await writeFile(MANIFEST, source, 'utf8');
  console.log(`[images] wrote manifest for ${Object.keys(manifest).length} images.`);
}

main().catch((error) => {
  console.error('[images] failed:', error);
  process.exitCode = 1;
});
