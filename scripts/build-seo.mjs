/**
 * SEO artifact generator
 * ----------------------
 * Writes `public/sitemap.xml` and `public/robots.txt` from the *same* route
 * list and site URL used by the app, so canonicals, sitemap and robots can
 * never drift apart.
 *
 * The domain is not purchased yet. Set VITE_SITE_URL in the environment
 * (or .env) when the real domain is live and re-run `npm run build`.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const SITE_URL = (process.env.VITE_SITE_URL || 'https://cakencrush.example.com').replace(/\/+$/, '');

const ROUTES = [
  { path: '/', priority: '1.0', changefreq: 'monthly' },
  { path: '/menu', priority: '0.9', changefreq: 'weekly' },
  { path: '/custom-cakes', priority: '0.9', changefreq: 'monthly' },
  { path: '/gallery', priority: '0.7', changefreq: 'monthly' },
  { path: '/about', priority: '0.6', changefreq: 'yearly' },
  { path: '/contact', priority: '0.8', changefreq: 'yearly' },
];

const today = new Date().toISOString().slice(0, 10);

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${ROUTES.map(
  (route) => `  <url>
    <loc>${SITE_URL}${route.path === '/' ? '/' : route.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${route.changefreq}</changefreq>
    <priority>${route.priority}</priority>
  </url>`,
).join('\n')}
</urlset>
`;

const robots = `# Cake N Crush — robots.txt
# Generated by scripts/build-seo.mjs. Update VITE_SITE_URL, not this file.

User-agent: *
Allow: /

# There are no private areas, admin routes or carts to disallow.

Sitemap: ${SITE_URL}/sitemap.xml
`;

const root = process.cwd();
await writeFile(path.join(root, 'public/sitemap.xml'), sitemap, 'utf8');
await writeFile(path.join(root, 'public/robots.txt'), robots, 'utf8');

console.log(`[seo] sitemap.xml + robots.txt written for ${SITE_URL} (${ROUTES.length} routes)`);
if (SITE_URL.includes('example.com')) {
  console.warn('[seo] NOTE: placeholder domain in use — set VITE_SITE_URL before launch.');
}
